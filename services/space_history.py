@dataclass(frozen=True)
class HistoryEvent:
    month: int
    day: int
    year: int
    category: str
    text: str

    @property
    def category_name(self) -> str:
        return CATEGORIES[self.category]


EVENTS: list[HistoryEvent] = sorted((HistoryEvent(*row) for row in _RAW),
                                    key=lambda e: (e.month, e.day, e.year))


def events_for(month: int, day: int, category: str | None = None) -> list[HistoryEvent]:
    """События выбранного дня года (по возрастанию года)."""
    return [e for e in EVENTS if e.month == month and e.day == day and (category is None or e.category == category)]


def nearest(month: int, day: int, window: int = 7, category: str | None = None) -> list[tuple[int, HistoryEvent]]:
    """Ближайшие события вокруг даты: (смещение в днях от выбранной, событие). Год невисокосный."""
    from datetime import date
    base = date(2021, month, min(day, 28) if (month == 2 and day == 29) else day)
    found = []
    for e in EVENTS:
        if category is not None and e.category != category:
            continue
        d = date(2021, e.month, min(e.day, 28) if (e.month == 2 and e.day == 29) else e.day)
        shift = (d - base).days
        for candidate in (shift, shift - 365, shift + 365):
            if abs(candidate) <= window:
                found.append((candidate, e))
                break
    found.sort(key=lambda pair: (abs(pair[0]), pair[0], pair[1].year))
    return found


def years_ago(event: HistoryEvent, current_year: int) -> int:
    return current_year - event.year
